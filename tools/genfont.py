assert len(CHARS) == len(GLYPHS), (len(CHARS), len(GLYPHS))

rows = []
rows.append("#ifndef FONT_H")
rows.append("#define FONT_H")
rows.append("/* Auto-generated by tools/genfont.py. 5x7 font, 7 bytes/glyph. */")
rows.append("static const unsigned char font_data[%d][7] = {" % len(CHARS))
for ch in CHARS:
    g = GLYPHS[ch]
    assert len(g) == 7 and all(len(r) == 5 for r in g), ch
    vals = []
    for r in g:
        b = 0
        for i, c in enumerate(r):
            if c == '#':
                b |= 1 << (4 - i)
        vals.append("0x%02X" % b)
    rows.append("    { %s },  /* '%s' */" % (", ".join(vals), ch.replace("'", "\\'")))
rows.append("};")
rows.append("")
chars_c = CHARS.replace("\\", "\\\\").replace('"', '\\"')
rows.append("static const char font_chars[] = \"%s\";" % chars_c)
rows.append("")
rows.append("static const unsigned char *font_glyph(char ch) {")
rows.append("    const char *p = font_chars;")
rows.append("    while (*p) { if (*p == ch) return font_data[p - font_chars]; p++; }")
rows.append("    return 0;")
rows.append("}")
rows.append("#endif")

with open("font.h", "w") as f:
    f.write("\n".join(rows) + "\n")
print("font.h written: %d glyphs, %d bytes" % (len(CHARS), len(CHARS) * 7))
